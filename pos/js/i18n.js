let current = localStorage.getItem('pos_lang') || 'es';
const listeners = new Set();

export function getLang() { return current; }

export function setLang(code) {
  if (!DICT[code]) return;
  current = code;
  localStorage.setItem('pos_lang', code);
  document.documentElement.lang = code === 'pap' ? 'pap' : code;
  listeners.forEach((fn) => fn(code));
}

export function onLangChange(fn) { listeners.add(fn); return () => listeners.delete(fn); }

// t('clave', {n: 3}) -> texto en el idioma actual, con fallback a español.
export function t(key, vars) {
  let s = (DICT[current] && DICT[current][key]) ?? DICT.es[key] ?? key;
  if (vars) for (const k in vars) s = s.replace(`{${k}}`, vars[k]);
  return s;
}
